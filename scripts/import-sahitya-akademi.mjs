// Reads src/data/imports/sahitya-akademi-kannada.csv (Kannada awards of the Sahitya Akademi, with the owner's festival-speaker matches)
// and writes src/data/sahitya-akademi-kannada.generated.js. Run: node scripts/import-sahitya-akademi.mjs
import { readFile, writeFile } from 'node:fs/promises'

function parseCsv(text) {
  const rows = []; let row = [], field = '', quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) { if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++ } else quoted = false } else field += c }
    else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(field); field = ''; if (row.some(v => v !== '')) rows.push(row); row = [] }
    else field += c
  }
  if (field !== '' || row.length) { row.push(field); if (row.some(v => v !== '')) rows.push(row) }
  return rows
}
const text = await readFile(new URL('../src/data/imports/sahitya-akademi-kannada.csv', import.meta.url), 'utf8')
const [header, ...rows] = parseCsv(text)
const col = Object.fromEntries(header.map((name, i) => [name.trim(), i]))
for (const name of ['winner', 'award_year', 'award', 'work', 'spoke_at_a_tracked_festival']) if (!(name in col)) throw new Error(`Missing column ${name}`)
const yes = value => value.trim().toLowerCase() === 'yes'
const awards = rows.map((r, i) => {
  const get = name => (r[col[name]] || '').trim()
  const year = Number(get('award_year'))
  if (!get('winner') || !Number.isInteger(year) || year < 1950 || year > 2100) throw new Error(`Row ${i + 2}: bad winner or year`)
  const spoke = yes(get('spoke_at_a_tracked_festival'))
  return {
    winner: get('winner'), year, award: get('award'), work: get('work'),
    festivals: spoke ? { confidence: get('match_confidence'), list: get('festivals_and_years'), sameOrNextYear: yes(get('same_or_next_year_as_award')), before: yes(get('spoke_before_award')), after: yes(get('spoke_after_award')) } : null,
  }
})
const out = `// Generated by scripts/import-sahitya-akademi.mjs from src/data/imports/sahitya-akademi-kannada.csv. Do not edit by hand.\nexport const sahityaAkademiRows = ${JSON.stringify(awards, null, 1)}\n`
await writeFile(new URL('../src/data/sahitya-akademi-kannada.generated.js', import.meta.url), out)
console.log('rows', awards.length, 'with festival match', awards.filter(a => a.festivals).length)
