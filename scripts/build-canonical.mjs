import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { canonicalGeoJSON, importCanonical, stageSourceRecords, validateCanonicalDataset } from '../src/data/canonical/pipeline.js'

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')
const args=process.argv.slice(2),inputArgs=args.filter(value=>!value.startsWith('--'))
const inputs=inputArgs.length?inputArgs.map(value=>path.resolve(process.cwd(),value)):[path.join(root,'fixtures/canonical/ec-sample.json'),path.join(root,'fixtures/canonical/ei-sample.json')]
const outputOnly=args.includes('--validate-only')
const staged=[]
for(const file of inputs){
  const payload=JSON.parse(fs.readFileSync(file,'utf8'))
  staged.push(...stageSourceRecords({corpus:payload.corpus,source:payload.source,records:payload.records,importedAt:null}))
}
const dataset=importCanonical(staged,{generatedAt:null}),issues=validateCanonicalDataset(dataset),errors=issues.filter(issue=>issue.severity==='error')
if(issues.length)console.log(issues.map(issue=>`${issue.severity.toUpperCase()} ${issue.collection}.${issue.id} ${issue.path}: ${issue.message}`).join('\n'))
if(errors.length){console.error(`Canonical validation failed with ${errors.length} error(s).`);process.exit(1)}
if(!outputOnly){
  const dataDirectory=path.join(root,'public/data/canonical'),moduleFile=path.join(root,'src/data/canonical/ec-ei-canonical.generated.js')
  fs.mkdirSync(dataDirectory,{recursive:true})
  fs.writeFileSync(moduleFile,`// Generated by scripts/build-canonical.mjs. Do not edit by hand.\nexport const canonicalData=${JSON.stringify(dataset,null,2)}\n`)
  fs.writeFileSync(path.join(dataDirectory,'entities.json'),`${JSON.stringify(dataset,null,2)}\n`)
  fs.writeFileSync(path.join(dataDirectory,'index.json'),`${JSON.stringify(dataset.indexes,null,2)}\n`)
  fs.writeFileSync(path.join(dataDirectory,'inscriptions.geojson'),`${JSON.stringify(canonicalGeoJSON(dataset),null,2)}\n`)
}
console.log(`Canonical pipeline OK: ${dataset.entities.source_records.length} source records, ${dataset.entities.inscriptions.length} inscriptions, ${errors.length} errors.`)
