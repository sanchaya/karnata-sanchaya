#!/usr/bin/env python3
"""Reads the OCR text of three Kannada University (Hampi) folk-game studies from the Internet Archive and writes
data/imports/folk-game-catalogues.json: the game names as printed in each study's catalogue, with the printed item number
where the study numbers its items. Names only, no descriptions or rules.

  python3 scripts/extract-folk-game-catalogues.py DIR     # DIR holds <identifier>.txt for the identifiers below

Method and limits: OCR is imperfect. Chitradurga items are read from the numbered lists in chapter 4 section 3 (a few numbers are
missing where the OCR dropped them). Bidar names are kept only when they appear as headings in both versions of the thesis
(2006 and 2009). The Ballari Beda list is curated by hand from the headings. Check each name against the page image."""
import json, re, sys
from pathlib import Path

KN = '೦೧೨೩೪೫೬೭೮೯'
def num(s): return int(''.join(str(KN.index(c)) if c in KN else c for c in s))
def lines(path): return Path(path).read_text(encoding='utf8').split('\n')

def chitradurga(path):
    L = lines(path)
    # (start line, end line, group id): the numbering restarts in each group of chapter 4 section 3
    groups = [(7000, 9890, 'strength-outdoor'), (9890, 11500, 'mind-indoor'), (11500, 12800, 'festival-tradition'),
              (12800, 13250, 'animal-bird'), (13250, 13700, 'fun-contests')]
    out = {g: [] for _, _, g in groups}
    for a, b, g in groups:
        for i in range(a, b):
            m = re.match(r'^([೦-೯0-9]{1,3})\s*[\.\)]\s*([^\d೦-೯]{3,60})$', L[i].strip())
            t = m and m.group(2).strip()
            if m and not t.endswith(('.', ',', ':')) and len(t.split()) <= 7 and 'ಹಾಗೂ' not in t and 'ಎಂಬ' not in t:
                if num(m.group(1)) == 2 and g == 'strength-outdoor' and not out[g]: continue
                out[g].append({'n': num(m.group(1)), 'name': t})
    return out

def bidar(p2006, p2009):
    def heads(path):
        d = {}
        for i, l in enumerate(lines(path)):
            t = l.strip()
            if i > 250 and 3 < len(t) <= 40 and re.search(r'ಆಟ[ಃ:]$', t):
                name = re.sub(r'^[^ಀ-೿]+', '', re.sub(r'[ಃ:]$', '', t)).strip()
                d.setdefault(re.sub(r'[\s\-\(\)ಃ:‌‍]', '', name), name)
        return d
    a, b = heads(p2006), heads(p2009)
    return [a[k] for k in a if k in b]

if __name__ == '__main__':
    d = Path(sys.argv[1])
    out = {'chitradurga': chitradurga(d / 'kuh.752.nir.132328.txt'),
           'bidar': bidar(d / 'kuh.mphil.293.vad.129930.txt', d / 'kuh.mphil.248.vad.129884.txt')}
    Path('data/imports/folk-game-catalogues.json').write_text(json.dumps(out, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
    js='// Generated by scripts/extract-folk-game-catalogues.py from OCR text of the studies named there. Names only; check against the page images.\nexport const folkCatalogueNames = '+json.dumps(out, ensure_ascii=False, indent=1)+'\n'
    Path('src/data/folk-game-catalogues.generated.js').write_text(js, encoding='utf8')
    print({k: (sum(len(v) for v in x.values()) if isinstance(x, dict) else len(x)) for k, x in out.items()})
