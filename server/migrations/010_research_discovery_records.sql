CREATE TABLE IF NOT EXISTS research_discovery_records (
  record_id VARCHAR(191) PRIMARY KEY,
  provider VARCHAR(120) NOT NULL,
  dataset_name VARCHAR(64) NOT NULL,
  record_kind VARCHAR(96) NOT NULL,
  scope_name VARCHAR(80) NOT NULL,
  title TEXT NOT NULL,
  source_url VARCHAR(2048) NULL,
  source_hash CHAR(64) NOT NULL,
  source_payload_json LONGTEXT NOT NULL,
  editorial_payload_json LONGTEXT NULL,
  review_status ENUM('needs-review','in-progress','reviewed','rejected') NOT NULL DEFAULT 'needs-review',
  reviewed_by CHAR(36) NULL,
  reviewed_at DATETIME(3) NULL,
  managed_by ENUM('repository','administrator') NOT NULL DEFAULT 'repository',
  sync_token CHAR(36) NULL,
  source_updated_at DATE NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_research_discovery_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL,
  KEY idx_research_discovery_dataset_status (dataset_name, review_status),
  KEY idx_research_discovery_provider_kind (provider, record_kind),
  KEY idx_research_discovery_sync (managed_by, sync_token)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
