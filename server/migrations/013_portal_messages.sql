CREATE TABLE IF NOT EXISTS portal_messages (
  id CHAR(36) PRIMARY KEY,
  reference_code VARCHAR(32) NOT NULL,
  user_id CHAR(36) NULL,
  sender_name VARCHAR(160) NULL,
  sender_email VARCHAR(254) NULL,
  category VARCHAR(80) NOT NULL,
  subject VARCHAR(255) NOT NULL,
  message TEXT NOT NULL,
  locale ENUM('kn','en') NOT NULL DEFAULT 'kn',
  source_deployment ENUM('live','github-pages') NOT NULL DEFAULT 'live',
  page_url VARCHAR(1000) NULL,
  record_id VARCHAR(191) NULL,
  status ENUM('new','triaged','in-progress','replied','closed','spam') NOT NULL DEFAULT 'new',
  assigned_to CHAR(36) NULL,
  admin_note TEXT NULL,
  ip_hash CHAR(64) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  closed_at DATETIME(3) NULL,
  UNIQUE KEY uq_portal_messages_reference (reference_code),
  KEY idx_portal_messages_queue (status, created_at),
  KEY idx_portal_messages_category (category, created_at),
  CONSTRAINT fk_portal_messages_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_portal_messages_assignee FOREIGN KEY (assigned_to) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
